function Home() {
  const navigate = useNavigate()
  const [products, setProducts] = useState<Product[]>([])
  const [loadingProducts, setLoadingProducts] = useState(true)
  const [orderingId, setOrderingId] = useState<number | null>(null)
  const [user, setUser] = useState<Awaited<ReturnType<typeof supabase.auth.getUser>>['data']['user']>(null)
  const [isAdmin, setIsAdmin] = useState(false)
  const [checkingUser, setCheckingUser] = useState(true)

  useEffect(() => {
    void loadProducts()
    void checkUser()
    const { data: { subscription } } = supabase.auth.onAuthStateChange(() => { void checkUser() })
    return () => subscription.unsubscribe()
  }, [])

  async function checkUser() {
    setCheckingUser(true)
    try {
      const { data: { user: currentUser } } = await supabase.auth.getUser()
      setUser(currentUser)
      if (currentUser) {
        const { data: profile } = await supabase.from('profiles').select('role').eq('id', currentUser.id).single()
        setIsAdmin(profile?.role === 'admin')
      } else setIsAdmin(false)
    } catch (error) {
      console.error('Error al verificar usuario:', error)
      setUser(null)
      setIsAdmin(false)
    } finally {
      setCheckingUser(false)
    }
  }

  async function loadProducts() {
    setLoadingProducts(true)
    try {
      const { data, error } = await supabase.from('products').select('id, name, description, price, image_url, active').eq('active', true).order('created_at', { ascending: false })
      if (error) {
        console.error('Error cargando productos:', error)
        setProducts([])
      } else {
        setProducts((data ?? []) as Product[])
      }
    } catch (error) {
      console.error('Error cargando productos:', error)
      setProducts([])
    } finally {
      setLoadingProducts(false)
    }
  }

  async function handleLogout() { await supabase.auth.signOut(); setUser(null); setIsAdmin(false); navigate({ to: '/' }) }
  function formatPrice(price: number) { return new Intl.NumberFormat('es-CO', { style: 'currency', currency: 'COP', maximumFractionDigits: 0 }).format(price) }

  async function createOrder(product: Product) {
    setOrderingId(product.id)
    try {
      const { data: { user: currentUser } } = await supabase.auth.getUser()
      if (!currentUser) { alert('Debes iniciar sesión para realizar un pedido.'); navigate({ to: '/login' }); return }
      const { error } = await supabase.rpc('create_order_with_balance', { p_product_id: product.id })
      if (error) { alert('No se pudo crear el pedido: ' + error.message); return }
      alert(`Pedido creado correctamente.\n\nServicio: ${product.name}\nPrecio: ${formatPrice(Number(product.price))}`)
      window.open(waLink(product.name), '_blank', 'noopener,noreferrer')
    } catch (error) {
      console.error(error)
      alert('Ocurrió un error al crear el pedido.')
    } finally {
      setOrderingId(null)
    }
  }

  return <div className="min-h-screen bg-black text-white">
    <header className="fixed top-0 left-0 right-0 z-50 bg-black/80 backdrop-blur-md border-b border-gray-800"><div className="max-w-7xl mx-auto px-4 py-4 flex items-center justify-between gap-4"><div className="flex items-center gap-3"><div className="rounded-full bg-blue-600/20 p-2"><Smartphone className="text-blue-400" size={22} /></div><div><p className="text-xs uppercase tracking-[0.2em] text-blue-400">Team Uverley</p><p className="text-sm text-gray-400">Servicios online</p></div></div><nav className="hidden md:flex items-center gap-6 text-sm text-gray-300"><a href="#servicios" className="hover:text-white">Servicios</a><a href="#por-que" className="hover:text-white">¿Por qué elegirnos?</a><a href="#contacto" className="hover:text-white">Contacto</a>{!user ? <Link to="/login" className="bg-blue-600 hover:bg-blue-700 px-4 py-2 rounded-lg">Iniciar sesión</Link> : <div className="flex items-center gap-2"><Link to="/account" className="flex items-center gap-2 text-gray-200 hover:text-white"><User size={16} /> Mi cuenta</Link>{isAdmin && <Link to="/dashboard" className="flex items-center gap-2 text-gray-200 hover:text-white"><Settings size={16} /> Dashboard</Link>}<button onClick={handleLogout} className="flex items-center gap-2 text-gray-200 hover:text-white"><LogOut size={16} /> Salir</button></div>}</nav>{user ? <Link to="/topup" className="hidden md:flex items-center gap-2 bg-green-600 hover:bg-green-700 px-4 py-2 rounded-lg text-sm font-semibold"><Wallet size={16} /> Recargar</Link> : null}</div></header>
    <section className="min-h-screen flex items-center justify-center px-4 pt-24 bg-gradient-to-b from-black via-gray-950 to-black"><div className="max-w-5xl mx-auto text-center"><p className="text-blue-400 uppercase tracking-[0.35em] text-xs font-bold mb-6">Team Uverley</p><h1 className="text-5xl md:text-7xl font-black mb-6 leading-tight">Servicios rápidos, seguros y confiables.</h1><p className="text-xl text-gray-300 max-w-3xl mx-auto mb-10">Compra tus servicios con atención directa, soporte real y una experiencia clara para usuarios y administradores.</p><div className="flex flex-col sm:flex-row justify-center items-center gap-4"><a href="#servicios" className="bg-blue-600 hover:bg-blue-700 px-7 py-4 rounded-xl font-bold">Ver servicios</a><a href={WA_BASE} target="_blank" rel="noopener noreferrer" className="border border-gray-700 bg-gray-900 hover:bg-gray-800 px-7 py-4 rounded-xl font-bold inline-flex items-center gap-2"><MessageCircle size={18} /> Chatear por WhatsApp</a></div></div></section>
    <section id="servicios" className="py-20 px-4"><div className="max-w-7xl mx-auto"><h2 className="text-4xl font-black text-center mb-14">Nuestros Servicios</h2>{loadingProducts ? <p className="text-center text-gray-400">Cargando servicios...</p> : products.length === 0 ? <div className="text-center text-gray-400 bg-gray-900/60 border border-gray-800 rounded-2xl p-10">Todavía no hay servicios activos disponibles.</div> : <div className="grid md:grid-cols-2 xl:grid-cols-3 gap-6">{products.map((product) => <div key={product.id} className="bg-gray-900/70 border border-gray-800 rounded-2xl overflow-hidden shadow-lg shadow-black/20"><div className="h-56 bg-gradient-to-br from-gray-800 to-gray-950 flex items-center justify-center overflow-hidden">{product.image_url ? <img src={product.image_url} alt={product.name} className="w-full h-full object-cover" /> : <div className="text-gray-500 text-center px-4"><Smartphone size={32} className="mx-auto mb-2" /><p>Sin imagen</p></div>}</div><div className="p-6"><div className="flex items-center justify-between gap-3 mb-3"><h3 className="text-xl font-bold">{product.name}</h3><span className="text-xs bg-green-900 text-green-300 px-2 py-1 rounded-full">Disponible</span></div><p className="text-gray-400 min-h-[72px]">{product.description || 'Descripción del servicio disponible.'}</p><div className="mt-5 flex items-center justify-between"><span className="text-2xl font-black text-green-400">{formatPrice(product.price)}</span><button onClick={() => void createOrder(product)} disabled={orderingId === product.id} className="bg-blue-600 hover:bg-blue-700 disabled:opacity-50 px-4 py-2 rounded-lg font-bold">{orderingId === product.id ? 'Procesando...' : 'Solicitar'}</button></div></div></div>)}</div>}</div></section>
    <section id="por-que" className="py-20 px-4 bg-gray-950/50"><div className="max-w-7xl mx-auto"><h2 className="text-4xl font-black text-center mb-14">¿Por qué elegirnos?</h2><div className="grid sm:grid-cols-2 lg:grid-cols-4 gap-6">{whyUs.map((item, index) => <div key={index} className="bg-gray-900/70 border border-gray-800 rounded-2xl p-6 text-center"><div className="flex justify-center mb-4">{item.icon}</div><h3 className="text-xl font-bold mb-2">{item.title}</h3><p className="text-gray-400">{item.desc}</p></div>)}</div></div></section>
    <section id="contacto" className="py-24 px-4 bg-gradient-to-b from-gray-950 to-black text-center"><h2 className="text-4xl md:text-5xl font-black mb-6">¿Necesitas ayuda?</h2><p className="text-gray-300 text-lg max-w-2xl mx-auto mb-8">Nuestro equipo está listo para resolver dudas, confirmar tus pedidos y ayudarte en cada paso.</p><div className="flex flex-col sm:flex-row items-center justify-center gap-4"><a href={WA_BASE} target="_blank" rel="noopener noreferrer" className="bg-green-600 hover:bg-green-700 px-6 py-4 rounded-xl font-bold inline-flex items-center gap-2"><MessageCircle size={20} /> Contactar por WhatsApp</a>{user ? <Link to="/account" className="bg-gray-800 hover:bg-gray-700 px-6 py-4 rounded-xl font-bold inline-flex items-center gap-2"><User size={20} /> Mi cuenta</Link> : <Link to="/login" className="bg-blue-600 hover:bg-blue-700 px-6 py-4 rounded-xl font-bold inline-flex items-center gap-2"><CheckCircle size={20} /> Iniciar sesión</Link>}</div></section>
  </div>
}












































































































































































































































































































































































































































































































































































